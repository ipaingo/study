const fs = require("fs");
const path = require("path");
const {
  AlignmentType, Document, LevelFormat, Packer, Paragraph, TextRun,
} = require("docx");

const outputPath = process.argv[2];
if (!outputPath) throw new Error("Usage: node build_reflection.js /abs/output.docx");

const T = String.raw;
const font = { ascii: "Arial", hAnsi: "Arial", cs: "Arial", eastAsia: "Arial" };

const run = (text, o = {}) => new TextRun({ text, font, size: 23, ...o });
const para = (children, o = {}) => new Paragraph({
  spacing: { after: 40, line: 220 }, ...o,
  children: Array.isArray(children) ? children : [children],
});
const body = (t) => para(run(t));
const q = (t) => para(run(t, { bold: true }), { spacing: { before: 80, after: 40 } });
const dashItem = (t) => para(run(t), {
  numbering: { reference: "dash", level: 0 }, spacing: { after: 15, line: 220 },
});

const children = [];

