children.push(body(T`Начала с конспекта курса: раздел "Как анализировать бизнес-стратегию" (4 вопроса) и материалы про North Star Metric и деревья метрик. Затем внимательно разобрала бриф TechGourmet. Методологию добирала в интернете: по driver-based подходу к ОПиУ (прибыль собирается из продуктовых драйверов), по кейсу Facebook "7 друзей за 10 дней" как примеру NSM, поведенческого предиктора удержания, и по бенчмаркам LTV/CAC (норма >= 3:1).`));
children.push(body(T`Расчетный инструмент - driver-based модель в Excel (Прибыль = Выручка * Gross Margin - OPEX; GMV = Клиенты * Frequency * Чек): полноценная финмодель без структуры расходов в брифе невозможна, а так каждый рубль прибыли привязан к продуктовому рычагу. Ключевые выводы модели: прибыль растет за счет frequency (+40%), маржи (+4 п.п.) и чека (+5%), а не привлечения, потому что LTV/CAC ~0,4. NSM выбрала "клиенты с 2+ заказами в месяц" - она фиксирует ценность (второй заказ возможен только после хорошей первой доставки) и ведет к цели по frequency. Дерево построила на 20 метрик, формулы связей указала на стрелках; для удобной перерисовки в Miro сначала набросала дерево в виде HTML-схемы, потом перенесла.`));
children.push(body(T`Свою работу проверяла так: перечитывала каждую часть глазами "враждебного проверяющего" - где преподаватель сможет меня подловить. Примеры правок: заменила строку "операционные рычаги не считаются численно" на расчетный "пакет качества"; усилила вывод, что эластичность доли повторных не зависит от допущения о frequency ядра и равна ровно 0,50; привела guardrail по отменам к единой истории (в части 2 было "<= 5%", в части 4 - "<= 6%, цель 5%").`));
children.push(body(T`Главная сложность - объем: итог надо было уложить в 5 страниц Word 12 кеглем, работа сжималась с 9 до 7 и до 5 страниц, таблицы ушли в 7,5 пт. Отдельная возня - с недопустимыми по требованию группы символами (длинные тире, >=, <=, знак рубля, умножения).`));
children.push(body(T`Честно поныть про бриф: данные противоречили друг другу, и это оказалось труднее самой стратегии. Выручка 180 млн не сходится с GMV (120 тыс. заказов * 1 400 руб. = 168 млн); retention 32%/мес при базе 100 тыс. дает стационарную базу ~18 тыс.; CPA 1 200 руб. при LTV ~476 руб. делает платное привлечение убыточным; CR на главной 15% выше CR регистрация -> покупка 10% - воронка "перевернута". А метрики противоречат самой стратегии: "скорость" при 48 минутах доставки, "качество" при NPS 35. Каждую несостыковку пришлось либо объяснять гипотезой, либо фиксировать допущение: 12 млн руб. трактовала как прочую выручку, а OPEX в брифе не дан - калибровала его под прибыль 10 млн руб. Преподаватель потом подтвердила, что несостыковки намеренные.`));

