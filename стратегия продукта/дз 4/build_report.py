def para(text, bold=False, indent=True, size=12, align=WD_ALIGN_PARAGRAPH.JUSTIFY,
         space_after=4, italic=False, color=None):
    p = doc.add_paragraph()
    p.alignment = align
    p.paragraph_format.first_line_indent = Cm(0.5) if indent else Cm(0)
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.line_spacing_rule = WD_LINE_SPACING.SINGLE
    r = p.add_run(text)
    r.font.name = "Arial"; r.font.size = Pt(size); r.bold = bold; r.italic = italic
    if color: r.font.color.rgb = RGBColor(*color)
    return p

def h1(text):
    return para(text, bold=True, indent=False, size=14, space_after=6)

def h2(text):
    return para(text, bold=True, indent=False, size=12, space_after=4)

def bullets(items, size=10.5):
    for it in items:
        p = doc.add_paragraph(style="List Bullet")
        p.paragraph_format.first_line_indent = Cm(0)
        p.paragraph_format.space_after = Pt(2)
        p.paragraph_format.line_spacing_rule = WD_LINE_SPACING.SINGLE
        r = p.add_run(it); r.font.name = "Arial"; r.font.size = Pt(size)

def shade(cell, hexcolor):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd"); shd.set(qn("w:val"), "clear"); shd.set(qn("w:fill"), hexcolor)
    tcPr.append(shd)

def table(headers, rows, widths=None, font=10, header_fill="D9E2F3"):
    t = doc.add_table(rows=1 + len(rows), cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    for j, htxt in enumerate(headers):
        c = t.rows[0].cells[j]; shade(c, header_fill)
        p = c.paragraphs[0]; p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.first_line_indent = Cm(0); p.paragraph_format.space_after = Pt(0)
        r = p.add_run(htxt); r.font.name = "Arial"; r.font.size = Pt(font); r.bold = True
    for i, row in enumerate(rows):
        for j, val in enumerate(row):
            c = t.rows[i + 1].cells[j]
            p = c.paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.LEFT
            p.paragraph_format.first_line_indent = Cm(0); p.paragraph_format.space_after = Pt(0)
            r = p.add_run(val); r.font.name = "Arial"; r.font.size = Pt(font)
    if widths:
        grid = t._tbl.find(qn("w:tblGrid"))
        for col, w in zip(grid.findall(qn("w:gridCol")), widths):
            col.set(qn("w:w"), str(int(w * 567)))
        for j, w in enumerate(widths):
            for row in t.rows:
                row.cells[j].width = Cm(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(0)
    return t

