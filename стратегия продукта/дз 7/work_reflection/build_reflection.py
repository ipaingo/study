with edit_docx(WORK_DIR) as doc:
    body = doc._element.body
    for child in list(body):
        if not child.tag.endswith("}sectPr"):
            body.remove(child)

    for text, kind in sections:
        p = doc.add_paragraph()
        pf = p.paragraph_format
        pf.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        pf.space_after = Pt(4)
        pf.space_before = Pt(7 if kind == "heading" else 0)
        pf.line_spacing = 1.0
        if kind == "body":
            pf.first_line_indent = Pt(14.2)
        elif kind == "list":
            pf.left_indent = Pt(14.2)
            pf.first_line_indent = Pt(0)
        else:
            pf.first_line_indent = Pt(14.2)
            pf.keep_with_next = True
        run = p.add_run(text)
        run.font.name = "Arial"
        run.font.size = Pt(11)
        run.bold = kind == "heading"

